"""
Tests of how Output turns the files of the backend into HDF5 files, one for each partition: what the files hold (the stars of the
partition, the groups, the attributes, the logs of the backend), the redefinition of the partitions by a rule of the user, and the
parser of the logs of the backend. The files of the backend are synthetic (see synthetic.py).
"""
import json
import os

import ebf
import h5py
import numpy as np
import pytest

from ..galaxia_ananke._builtin_utils import metadata_dicts_to_consolidated_json
from ..galaxia_ananke._constants import NAME, PARENTPARTICLE_GROUP, PARTITIONING_GROUP, STARCATALOG_GROUP
from ..galaxia_ananke.__metadata__ import __url__, __version__
from ..galaxia_ananke.Output import Output
from .synthetic import log_text, prepared_survey, write_backend_output, write_ebf


def read_h5(path):
    with h5py.File(path, 'r') as f5:
        return {'groups': {group: {key: f5[group][key][...] for key in f5[group]} for group in f5}, 'attrs': dict(f5.attrs)}


def read(tmp_path, monkeypatch, n_gens=(0,), max_pp_workers=1, pp_auto_flush=False, rule=None, **backend):
    survey = prepared_survey(tmp_path, monkeypatch, n_gens=n_gens)
    written = write_backend_output(survey, **backend)
    survey.output.read_galaxia_output(rule, max_pp_workers, pp_auto_flush)
    return survey.output, written


def odd_or_even_px(df):
    return (df['px'].to_numpy() % 2).astype(int)


# -- what the files hold ------------------------------------------------------------

def test_the_stars_are_written_in_one_file_that_has_a_dataset_for_each_exported_key(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_stars=5)
    h5 = read_h5(output._hdf5s[0])
    assert list(output._hdf5s) == [0]
    assert set(h5['groups']) == {STARCATALOG_GROUP, PARENTPARTICLE_GROUP, PARTITIONING_GROUP}
    stars = h5['groups'][STARCATALOG_GROUP]
    assert set(stars) == set(output.export_keys)
    for key, column in written[0][1].items():
        assert stars[key].dtype == column.dtype and stars[key].tolist() == column.tolist()


def test_the_group_of_the_parent_particles_is_made_and_is_empty_until_the_catalogue_is_post_processed(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5)
    assert read_h5(output._hdf5s[0])['groups'][PARENTPARTICLE_GROUP] == {}


def test_the_attributes_of_a_file_say_where_it_comes_from_and_which_partition_it_is(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5)
    h5 = read_h5(output._hdf5s[0])
    assert h5['attrs']['Header'] == f"File generated by Python module {NAME} v{__version__}, software available at <{__url__}>."
    assert h5['attrs']['Cat_partition_id'] == 0
    assert h5['attrs']['All_partition_ids'] == f"Stored under dataset {PARTITIONING_GROUP}/partition_id"
    assert h5['groups'][PARTITIONING_GROUP]['partition_id'].tolist() == [0]


def test_the_attributes_of_a_file_have_all_the_metadata_of_the_output(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5)
    attrs = read_h5(output._hdf5s[0])['attrs']
    assert {key: attrs[key] for key in output.all_metadata} == output.all_metadata


def test_the_attributes_of_a_file_have_the_logs_of_the_backend_for_the_stars_of_the_file(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_gens=(0, 1), n_stars=5)
    logs = json.loads(read_h5(output._hdf5s[0])['attrs']['Galaxia_ebf_output_logs'])
    parsed = [Output._Output__parse_galaxia_ebf_log(str(path.resolve())) for path in output._ebfs]
    assert logs == json.loads(metadata_dicts_to_consolidated_json(parsed, metadata_name="Galaxia_ebf_output_logs"))
    assert "17052" in json.dumps(logs) and "log made for the tests" in json.dumps(logs)


def test_each_partition_has_its_file_with_its_stars_and_the_list_of_all_the_partitions(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_stars=6, partitions=[0, 0, 1, 1, 1, 2])
    columns = written[0][1]
    for partition, stars in {0: [0, 1], 1: [2, 3, 4], 2: [5]}.items():
        h5 = read_h5(output._hdf5s[partition])
        assert h5['groups'][STARCATALOG_GROUP]['px'].tolist() == columns['px'][stars].tolist()
        assert h5['groups'][STARCATALOG_GROUP]['partitionid'].tolist() == [partition] * len(stars)
        assert h5['attrs']['Cat_partition_id'] == partition
        assert h5['groups'][PARTITIONING_GROUP]['partition_id'].tolist() == [0, 1, 2]


def expected_rows(output, written, key, partition, position):
    """The rows of a column in the file of a partition: those of each file of the backend in turn, from the one that comes
    `position` files after the first (the files are not all read from the first, so that the processes do not all start with it)."""
    by_name = {path.name: columns for path, columns in written}
    files = list(output._ebfs)
    turn = position % len(files)
    files = files[turn:] + files[:turn]
    return np.concatenate([by_name[f.name][key][by_name[f.name]['partitionid'] == partition] for f in files])


def test_the_stars_of_several_files_of_the_backend_are_put_together_in_each_partition(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_gens=(0, 1), n_stars=4, partitions=[0, 1, 1, 0])
    for position, partition in enumerate(output._hdf5s):
        stars = read_h5(output._hdf5s[partition])['groups'][STARCATALOG_GROUP]
        assert stars['px'].tolist() == expected_rows(output, written, 'px', partition, position).tolist()
        assert len(stars['px']) == 4


def test_the_stars_of_the_generations_come_in_the_order_of_the_generations_whatever_the_order_the_files_are_listed_in(tmp_path, monkeypatch):
    survey = prepared_survey(tmp_path, monkeypatch, n_gens=(0, 1))
    written = write_backend_output(survey, n_stars=3)
    listed = Output._ebf_glob.fget
    monkeypatch.setattr(Output, '_ebf_glob', property(lambda self: iter(sorted(listed(self), reverse=True))))      # the last generation first
    survey.output.read_galaxia_output(None, 1, False)
    px = read_h5(survey.output._hdf5s[0])['groups'][STARCATALOG_GROUP]['px']
    assert px.tolist() == np.concatenate([columns['px'] for _, columns in written]).tolist()


def test_the_files_of_the_backend_are_in_the_numeric_order_of_the_generations_and_not_in_the_order_of_their_names(tmp_path, monkeypatch):
    survey = prepared_survey(tmp_path, monkeypatch, n_gens=tuple(range(11)))
    write_backend_output(survey, n_stars=1)
    listed = Output._ebf_glob.fget
    monkeypatch.setattr(Output, '_ebf_glob', property(lambda self: iter(sorted(listed(self), reverse=True))))   # 9, 8, ..., 2, 10, 1, 0
    assert [int(path.stem.rsplit('.', 1)[-1]) for path in survey.output._ebfs] == list(range(11))


def test_the_files_of_the_backend_are_read_from_a_different_one_for_each_partition(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_gens=(0, 1), n_stars=2, partitions=[0, 1])
    first_of = lambda partition: read_h5(output._hdf5s[partition])['groups'][STARCATALOG_GROUP]['px'][0]
    by_name = {path.name: columns['px'] for path, columns in written}
    files = list(output._ebfs)
    assert first_of(0) in by_name[files[0].name] and first_of(1) in by_name[files[1].name]


# -- redefining the partitions ------------------------------------------------------

def test_without_a_rule_the_files_of_the_backend_are_not_touched(tmp_path, monkeypatch):
    survey = prepared_survey(tmp_path, monkeypatch)
    path = write_backend_output(survey, n_stars=6)[0][0]
    before = path.read_bytes()
    survey.output.read_galaxia_output(None, 1, False)
    assert path.read_bytes() == before


def test_a_rule_gives_the_partition_of_each_star_and_the_stars_go_to_the_file_of_their_partition(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_stars=6, rule=odd_or_even_px)
    columns = written[0][1]
    assert list(output._hdf5s) == [0, 1]
    even, odd = (read_h5(output._hdf5s[partition])['groups'][STARCATALOG_GROUP] for partition in (0, 1))
    assert sorted(even['px'].tolist()) == [2.0, 4.0, 6.0] and sorted(odd['px'].tolist()) == [1.0, 3.0, 5.0]
    assert even['partitionid'].tolist() == [0, 0, 0] and odd['partitionid'].tolist() == [1, 1, 1]
    original = set(zip(columns['px'].tolist(), columns['parentid'].tolist()))
    assert set(zip(even['px'].tolist(), even['parentid'].tolist())) | set(zip(odd['px'].tolist(), odd['parentid'].tolist())) == original
    assert set(zip(even['px'].tolist(), even['parentid'].tolist())) == {(2.0, 1), (4.0, 0), (6.0, 2)}      # the rows stay together


def test_the_file_of_the_backend_is_changed_by_a_rule_and_says_so_in_its_log(tmp_path, monkeypatch):
    survey = prepared_survey(tmp_path, monkeypatch)
    path = write_backend_output(survey, n_stars=6)[0][0]
    survey.output.read_galaxia_output(odd_or_even_px, 1, False)
    log = str(ebf.read(str(path), '/log'))
    assert log.startswith(log_text(0).rstrip('\n'))
    assert log.endswith(f"# Modified by Python's {NAME} v{__version__},\n# software available at <{__url__}>.\n")
    assert ebf.read(str(path), '/partitionid').tolist() == [0, 0, 0, 1, 1, 1]            # the stars are in the order of their partitions


# -- how it is run ------------------------------------------------------------------

def test_the_catalogue_is_loaded_when_the_partitions_are_not_flushed_by_themselves(tmp_path, monkeypatch):
    output, written = read(tmp_path, monkeypatch, n_stars=5, partitions=[0, 0, 1, 1, 1], pp_auto_flush=False)
    assert len(output._vaex) == 5 and sorted(output._vaex_per_partition) == [0, 1]
    assert [len(df) for df in output._vaex_per_partition.values()] == [2, 3]
    assert sorted(output._vaex['px'].to_numpy().tolist()) == sorted(written[0][1]['px'].tolist())


def test_the_catalogue_is_not_loaded_when_the_partitions_are_flushed_by_themselves(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5, pp_auto_flush=True)
    assert output._hdf5s[0].exists()
    with pytest.raises(RuntimeError, match="Don't attempt creating an Output object on your own"):
        output._vaex


def test_reading_sets_how_many_workers_there_are_and_whether_the_partitions_are_flushed_by_themselves(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5, max_pp_workers=2, pp_auto_flush=False)
    assert output._max_pp_workers == 2 and output._pp_auto_flush is False


def test_what_was_read_is_in_the_state_of_the_output(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5)
    state = json.loads((output.output_dir / f"{output.output_name}.state").read_text())
    assert state['description'] == 'convert_ebf_to_hdf5'


def test_without_caching_the_files_are_written_again_when_the_output_is_read_again(tmp_path, monkeypatch):
    output, _ = read(tmp_path, monkeypatch, n_stars=5)
    path = output._hdf5s[0]
    os.utime(path, (1_000_000_000, 1_000_000_000))
    output.read_galaxia_output(None, 1, False)
    assert path.stat().st_mtime > 1_000_001_000


# -- the log of the backend ---------------------------------------------------------

def parse(tmp_path, log):
    return Output._Output__parse_galaxia_ebf_log(str(write_ebf(tmp_path / 'log.ebf', {}, log=log).resolve()))


def test_a_log_is_made_of_a_header_the_parameters_that_it_gives_and_a_footer(tmp_path):
    assert parse(tmp_path, log_text(3)) == {'log_header': '# Galaxia (a log made for the tests) number 3',
                                            'outputFile': 'survey', 'fSample': '1', 'seed': '17052',
                                            'log_footer': '# End of the log number 3\n'}


def test_a_parameter_with_several_words_has_them_joined_by_a_space(tmp_path):
    assert parse(tmp_path, log_text(0, (('first', '1'), ('name', 'x  y\tz'))))['name'] == 'x y z'


def test_the_empty_lines_of_the_parameters_are_left_out(tmp_path):
    log = "# header\n# <parameterfile>\na\t1\n\n# b\t2\n# </parameterfile>\n# footer\n"
    assert parse(tmp_path, log) == {'log_header': '# header', 'a': '1', 'b': '2', 'log_footer': '# footer\n'}


def test_a_parameter_on_the_line_that_follows_the_tag_has_its_comment_sign_taken_for_its_name(tmp_path):
    # How it is today: the signs that are removed are those that follow a line break, and the first parameter has none before it.
    # The log of the real backend does not come that way (its first parameter has no sign, see test_integration.py): it is latent.
    log = "# header\n# <parameterfile>\n# a\t1\n# b\t2\n# </parameterfile>\n# footer\n"
    parsed = parse(tmp_path, log)
    assert parsed['#'] == 'a 1' and parsed['b'] == '2' and 'a' not in parsed


@pytest.mark.parametrize("log", [
    "# header\n# footer\n",
    "# header\n# <parameterfile>\na\t1\n# footer\n",
    "# h\n# <parameterfile>\na\t1\n# </parameterfile>\n# <parameterfile>\nb\t2\n# </parameterfile>\n# f\n",
], ids=["no tags", "no closing tag", "two parameter files"])
def test_a_log_that_does_not_have_one_parameter_file_between_its_tags_is_refused(log, tmp_path):
    with pytest.raises(ValueError):
        parse(tmp_path, log)


